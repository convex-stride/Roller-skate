import { chromium } from "@playwright/test";
import assert from "node:assert/strict";
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/usr/bin/chromium", args: ["--no-sandbox", "--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
try {
  const page = await browser.newPage({ viewport: { width: 1000, height: 720 } }), errors = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("console", m => { if (m.type() === "error" && /shader|THREE|WebGLProgram/i.test(m.text())) errors.push(m.text()); });
  await page.goto(process.env.GAME_URL || "http://127.0.0.1:4173");
  await page.getByRole("button", { name: "Find your line" }).click({ timeout: 60000 });
  await page.waitForFunction(() => window.__skate.state.grounded);
  assert.equal(await page.evaluate(() => window.__skate.state.riderName), "Layan");
  const origin = await page.evaluate(() => window.__skate.state.position);
  await page.keyboard.press("j");
  assert.equal(await page.locator("[data-quest]:visible").count(), 128);
  await page.locator('[data-map-city="gdansk"]').click();
  await page.screenshot({ path: "releases/layans-skate-96-quests.png" });
  const marker = await page.evaluate(() => window.__skate.destinations.find(d => d.id === "quest:quest-gdansk-0-0-community"));
  const mapCanvas = page.locator("#world-map"), rect = await mapCanvas.boundingBox();
  const pixels = await mapCanvas.evaluate(c => ({ w: c.width, h: c.height })), scale = Math.min(pixels.w / 1800, (pixels.h - 40) / 1800);
  await mapCanvas.click({ position: { x: (pixels.w / 2 + (marker.x + 1000) * scale) / pixels.w * rect.width, y: (pixels.h / 2 + marker.z * scale) / pixels.h * rect.height } });
  assert.equal(await page.evaluate(() => window.__skate.state.navigation.selected), marker.id, "quest markers can be selected directly on the map");
  await page.locator("#waypoint-clear").click();
  await page.getByRole("button", { name: "Landmarks", exact: true }).click();
  await page.locator("#map-search").fill("Żuraw");
  assert.equal(await page.locator("[data-landmark]:visible").count(), 1);
  await page.getByRole("button", { name: /^Explore: Żuraw/ }).click();
  const routed = await page.evaluate(() => window.__skate.state);
  assert.ok(Math.hypot(routed.position.x - origin.x, routed.position.z - origin.z) < 0.2, "guide selection does not teleport Layan");
  assert.ok(routed.navigation.routePoints > 1); assert.match(await page.locator("#map-selected-name").innerText(), /Żuraw/);
  await page.locator("#map-partner-guide").click();
  await page.waitForFunction(() => window.__skate.state.companion.active && window.__skate.state.companion.routePoints > 1);
  const partnerStart = await page.evaluate(() => window.__skate.state.companion.position);
  await page.waitForFunction(start => Math.hypot(window.__skate.state.companion.position.x - start.x, window.__skate.state.companion.position.z - start.z) > 3, partnerStart, { timeout: 60000 });
  await page.screenshot({ path: "releases/layans-skate-taqee-guiding.png" });
  await page.keyboard.press("p"); await page.locator('[data-partner="call"]').click();
  await page.locator('[data-partner="wait"]').click();
  const wait = await page.evaluate(() => ({ t: window.__skate.state.simTime, p: window.__skate.state.companion.position }));
  await page.keyboard.down("w");
  await page.waitForFunction(t => window.__skate.state.simTime > t + 3, wait.t);
  await page.keyboard.up("w");
  const stayed = await page.evaluate(() => window.__skate.state.companion.position);
  assert.ok(Math.hypot(stayed.x - wait.p.x, stayed.z - wait.p.z) < 0.7, "Wait keeps Taqee in place");
  await page.locator('[data-partner="call"]').click(); await page.locator('[data-partner="tricks"]').click();
  await page.waitForFunction(() => window.__skate.state.companion.jumps > 0);
  await page.screenshot({ path: "releases/layans-skate-taqee-tricks.png" });
  await page.locator('[data-partner="race"]').click();
  await page.waitForFunction(() => window.__skate.state.race?.status === "countdown");
  assert.deepEqual(await page.evaluate(() => window.__skate.state.race.standings.map(r => r.name)), ["Layan", "Taqee"]);
  await page.keyboard.down("w"); await page.keyboard.down("Shift");
  await page.waitForFunction(() => window.__skate.state.race?.status === "racing" && window.__skate.state.race.standings.some(r => r.name === "Taqee" && r.gate > 0), null, { timeout: 60000 });
  await page.screenshot({ path: "releases/layans-skate-layan-vs-taqee.png" });
  await page.waitForFunction(() => window.__skate.state.race?.status === "finished", null, { timeout: 120000 });
  await page.keyboard.up("w"); await page.keyboard.up("Shift");
  assert.equal(Object.keys(await page.evaluate(() => window.__skate.state.partnerRaceResults)).length, 1);
  assert.equal(Object.keys(await page.evaluate(() => window.__skate.state.raceResults)).length, 0);
  await page.locator("#race-leave").click();
  await page.waitForFunction(() => !window.__skate.state.companion.racing && window.__skate.state.companion.active);
  await page.reload(); await page.getByRole("button", { name: "Find your line" }).click({ timeout: 60000 });
  await page.waitForFunction(() => window.__skate.state.companion.active);
  assert.equal(Object.keys(await page.evaluate(() => window.__skate.state.partnerRaceResults)).length, 1);
  await page.keyboard.press("p"); await page.locator('[data-partner="dismiss"]').click();
  assert.equal(await page.evaluate(() => window.__skate.state.companion.active), false);
  await page.close();
  const phone = await browser.newPage({ viewport: { width: 393, height: 852 }, isMobile: true, hasTouch: true });
  phone.on("pageerror", e => errors.push(e.message));
  await phone.goto(process.env.GAME_URL || "http://127.0.0.1:4173");
  await phone.getByRole("button", { name: "Find your line" }).tap({ timeout: 60000 });
  await phone.waitForFunction(() => window.__skate.state.grounded);
  await phone.locator("#partner-toggle").tap();
  await phone.locator('[data-partner="follow"]').tap();
  assert.equal(await phone.evaluate(() => window.__skate.state.companion.active), true);
  await phone.screenshot({ path: "releases/layans-skate-phone-taqee.png" });
  const panel = await phone.locator("#partner-panel").boundingBox(); assert.ok(panel.x >= 0 && panel.x + panel.width <= 394 && panel.y + panel.height < 680);
  await phone.locator('[data-partner="close"]').tap();
  await phone.getByRole("button", { name: "Open world map", exact: true }).tap();
  await phone.getByRole("button", { name: "Quests", exact: true }).tap();
  await phone.locator('[data-map-city="riyadh"]').tap();
  await phone.locator('[data-quest="quest-riyadh-0-0-community"]').tap();
  await phone.locator("#map-partner-guide").tap();
  assert.equal(await phone.evaluate(() => window.__skate.state.companion.mode), "guide");
  await phone.setViewportSize({ width: 852, height: 393 });
  await phone.locator("#partner-toggle").tap();
  await phone.screenshot({ path: "releases/layans-skate-phone-taqee-landscape.png" });
  for (const selector of ["#partner-panel", "#touch-stick", ".touch-buttons"]) { const r = await phone.locator(selector).boundingBox(); assert.ok(r && r.x >= 0 && r.y >= 0 && r.x + r.width <= 853 && r.y + r.height <= 394, `${selector} fits landscape`); }
  assert.deepEqual(errors, []);
  console.log("Layan naming, 128 visible quests, city focus/search, route without teleport, physical Taqee guiding/waiting/tricks, completed duet and saved results, recall/dismiss and phone layouts passed; no runtime/shader errors.");
} finally { await browser.close(); }
