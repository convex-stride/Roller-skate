import { chromium } from "@playwright/test";
import assert from "node:assert/strict";
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/usr/bin/chromium", args: ["--no-sandbox", "--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
try {
  const context = await browser.newContext({ viewport: { width: 393, height: 852 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 });
  const page = await context.newPage(), errors = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("console", m => { if (m.type() === "error" && /shader|THREE|WebGLProgram/i.test(m.text())) errors.push(m.text()); });
  const client = await context.newCDPSession(page);
  const points = new Map();
  const send = type => client.send("Input.dispatchTouchEvent", { type, touchPoints: [...points].map(([id, p]) => ({ id, ...p, radiusX: 4, radiusY: 4, force: 1 })) });
  const center = async selector => { const r = await page.locator(selector).boundingBox(); assert.ok(r); return { x: r.x + r.width / 2, y: r.y + r.height / 2 }; };
  await page.goto(process.env.GAME_URL || "http://127.0.0.1:4173");
  await page.getByRole("button", { name: "Find your line" }).tap({ timeout: 60000 });
  await page.waitForFunction(() => window.__skate.state.grounded && window.__skate.state.touch.enabled);
  await page.locator("#touch-controls").waitFor({ state: "visible" });
  assert.equal(await page.evaluate(() => window.__skate.state.rendering.shadows), false);
  const stick = await center("#touch-stick");
  points.set(1, stick); await send("touchStart");
  points.set(1, { x: stick.x, y: stick.y - 42 }); await send("touchMove");
  await page.waitForFunction(() => window.__skate.state.speed > 3, null, { timeout: 30000 });
  points.set(2, await center('[data-hold="jump"]')); await send("touchStart");
  await page.waitForFunction(() => window.__skate.state.jumps > 0 && window.__skate.state.verticalSpeed > 2);
  assert.ok(await page.evaluate(() => window.__skate.state.touch.throttle > 0.8 && window.__skate.state.touch.jump));
  points.set(3, await center('[data-trick="left"]')); await send("touchStart");
  await page.waitForFunction(() => Math.abs(window.__skate.state.airRotation) > 0.3);
  await page.screenshot({ path: "releases/phone-portrait-v10.png" });
  points.clear(); await send("touchEnd");
  await page.waitForFunction(() => window.__skate.state.touch.throttle === 0 && !window.__skate.state.touch.jump);
  const look = await page.evaluate(() => window.__skate.state.cameraLook.yaw);
  points.set(4, { x: 185, y: 420 }); await send("touchStart");
  points.set(4, { x: 230, y: 440 }); await send("touchMove"); points.clear(); await send("touchEnd");
  assert.notEqual(await page.evaluate(() => window.__skate.state.cameraLook.yaw), look);
  await page.getByRole("button", { name: "Pause game", exact: true }).tap();
  await page.waitForFunction(() => window.__skate.state.paused);
  assert.equal(await page.locator("#touch-controls").isVisible(), false);
  await page.locator("#pause-settings").tap();
  await page.getByRole("tab", { name: /Camera & controls/ }).tap();
  await page.screenshot({ path: "releases/phone-settings-v10.png" });
  await page.locator("#settings-back").tap(); await page.locator("#resume").tap();
  await page.getByRole("button", { name: "Open world map", exact: true }).tap();
  await page.locator("#map-travel-mode").tap();
  await page.getByRole("button", { name: /^Ride: Rooftop leap/ }).tap();
  await page.waitForFunction(() => window.__skate.state.spot?.id === "garden-gap");
  await page.setViewportSize({ width: 852, height: 393 });
  await page.waitForFunction(() => window.innerWidth > window.innerHeight);
  await page.locator('[data-command="more"]').tap();
  await page.screenshot({ path: "releases/phone-landscape-v10.png" });
  for (const selector of ["#touch-stick", ".touch-buttons", ".touch-more", ".touch-toolbar"]) {
    const r = await page.locator(selector).boundingBox();
    assert.ok(r && r.x >= 0 && r.y >= 0 && r.x + r.width <= 853 && r.y + r.height <= 394, `${selector} fits the phone`);
  }
  assert.equal(await page.evaluate(() => window.__skate.state.touch.throttle), 0);
  // Pointer cancellation must release a held thumbstick, including interrupted gestures.
  const rotated = await center("#touch-stick");
  points.set(5, { x: rotated.x, y: rotated.y - 40 }); await send("touchStart");
  await page.waitForFunction(() => window.__skate.state.touch.throttle > 0.5);
  points.clear(); await send("touchCancel");
  await page.waitForFunction(() => window.__skate.state.touch.throttle === 0);
  const heading = await page.evaluate(() => window.__skate.state.heading);
  points.set(6, { x: rotated.x + 40, y: rotated.y }); await send("touchStart");
  await page.waitForFunction(h => Math.abs(window.__skate.state.heading - h) > 0.05, heading);
  points.clear(); await send("touchEnd");
  points.set(7, await center('[data-hold="brake"]')); await send("touchStart");
  await page.waitForFunction(() => window.__skate.state.touch.brake === 1);
  points.clear(); await send("touchEnd");
  await page.getByRole("button", { name: "Pause game", exact: true }).tap();
  await page.locator("#return-lobby").tap();
  await page.screenshot({ path: "releases/phone-lobby-landscape-v10.png" });
  await page.getByRole("button", { name: "Find your line" }).tap();
  await page.waitForFunction(() => !window.__skate.state.paused);
  assert.deepEqual(errors, []);
  console.log("Phone portrait/landscape: real multi-touch push+jump+spin, drag look, cancel cleanup, pause, settings and map travel passed; no runtime/shader errors.");
} finally { await browser.close(); }
