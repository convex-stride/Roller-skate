import { chromium } from "@playwright/test";
import assert from "node:assert/strict";
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/usr/bin/chromium", args: ["--no-sandbox", "--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 },deviceScaleFactor:Number(process.env.PHYSICS_TEST_DPR||1) }), errors = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("console", m => { if (m.type() === "error" && /shader|THREE|WebGLProgram/i.test(m.text())) errors.push(m.text()); });
  await page.goto(process.env.GAME_URL || "http://127.0.0.1:4173");
  if(process.env.LOW_GRAPHICS){await page.locator('#lobby-settings').click({timeout:90000});await page.locator('#quality').selectOption('0.5');await page.locator('#settings-apply').click();await page.locator('#settings-back').click();}
  await page.getByRole("button", { name: "Find your line" }).click({ timeout: 60000 });
  for (const [id, name] of [["race-motlawa", "Motława Dash"], ["race-olaya", "Olaya Boulevard Sprint"]]) {
    await page.keyboard.press("m"); await page.locator("#map-travel-mode").click(); await page.getByRole("button", { name: new RegExp(`^Race: ${name}`) }).click();
    await page.waitForFunction(() => window.__skate.state.race?.status === "countdown");
    const start = await page.evaluate(() => window.__skate.state);
    await page.keyboard.down("w");
    await page.waitForFunction(c => window.__skate.state.race.countdown < c - 0.8, start.race.countdown);
    const held = await page.evaluate(() => window.__skate.state);
    assert.ok(Math.hypot(held.position.x - start.position.x, held.position.z - start.position.z) < 0.05, "countdown holds the rider on the grid");
    await page.screenshot({ path: `releases/${id}-countdown-v12.png` });
    await page.keyboard.press("Escape");
    const paused = await page.evaluate(() => window.__skate.state.race.countdown);
    await page.screenshot({ path: `releases/${id}-paused-v12.png` });
    assert.equal(await page.evaluate(() => window.__skate.state.race.countdown), paused);
    await page.locator("#resume").click();
    await page.keyboard.down("w"); await page.keyboard.down("Shift");
    await page.waitForFunction(() => window.__skate.state.race?.status === "racing", null, { timeout: 30000 });
    await page.waitForFunction(() => window.__skate.state.speed > 3 && window.__skate.state.race.standings.some(r => r.id !== "player" && r.gate > 0), null, { timeout: 90000 });
    await page.screenshot({ path: `releases/${id}-racing-v12.png` });
    await page.waitForFunction(() => window.__skate.state.race?.status === "finished", null, { timeout: 120000 }).catch(async e => { console.log(await page.evaluate(() => window.__skate.state)); throw e; });
    await page.keyboard.up("w"); await page.keyboard.up("Shift");
    const finished = await page.evaluate(() => window.__skate.state);
    assert.equal(finished.race.gate, finished.race.totalGates);
    assert.ok(finished.raceResults[id].time > 0 && finished.raceResults[id].place <= 4);
    await page.screenshot({ path: `releases/${id}-result-v12.png` });
    console.log(JSON.stringify({ id, result: finished.raceResults[id], standings: finished.race.standings }));
    await page.locator("#race-leave").click();
  }
  await page.reload(); await page.getByRole("button", { name: "Find your line" }).click({ timeout: 60000 });
  assert.equal(Object.keys(await page.evaluate(() => window.__skate.state.raceResults)).length, 2, "race records survive save loading");
  await page.keyboard.press("m"); await page.locator("#map-travel-mode").click(); await page.getByRole("button", { name: /^Race: Dockyard Circuit/ }).click();
  await page.waitForFunction(() => window.__skate.state.race?.status === "racing");
  await page.locator("#race-restart").click();
  assert.equal(await page.evaluate(() => window.__skate.state.race.status), "countdown");
  await page.locator("#race-leave").click();
  assert.equal(await page.evaluate(() => window.__skate.state.race), null);
  assert.deepEqual(errors, []);
  await page.close();
  const phone = await browser.newPage({ viewport: { width: 393, height: 852 }, isMobile: true, hasTouch: true });
  phone.on("pageerror", e => errors.push(e.message));
  await phone.goto(process.env.GAME_URL || "http://127.0.0.1:4173");
  await phone.getByRole("button", { name: "Find your line" }).tap({ timeout: 60000 });
  await phone.getByRole("button", { name: "Open world map", exact: true }).tap();
  await phone.locator("#map-travel-mode").tap();
  await phone.getByRole("button", { name: /^Race: Motława Dash/ }).tap();
  await phone.waitForFunction(() => window.__skate.state.race?.status === "countdown");
  await phone.screenshot({ path: "releases/phone-race-v12.png" });
  await phone.getByRole("button", { name: "Restart race", exact: true }).tap();
  await phone.getByRole("button", { name: "Leave race", exact: true }).tap();
  await phone.waitForFunction(() => window.__skate.state.nearbyRace === "race-motlawa");
  await phone.getByRole("button", { name: "Join race", exact: true }).tap();
  await phone.waitForFunction(() => window.__skate.state.race?.status === "countdown");
  assert.deepEqual(errors, []);
  console.log("Countdown, pause, physical rivals, two completed sprints, standings, save reload, restart/leave and phone race entry passed; no runtime/shader errors.");
} finally { await browser.close(); }
